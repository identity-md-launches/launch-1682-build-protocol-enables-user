// Regenerates web/src/abi/swarmExit.ts from the Foundry artifact of src/SwarmExit.sol.
// Run `forge build` at the repository root first, then `node web/scripts/gen-abi.mjs`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const artifact = JSON.parse(fs.readFileSync(path.join(root, "out/SwarmExit.sol/SwarmExit.json"), "utf8"));
const sortKeys = (v) =>
  Array.isArray(v) ? v.map(sortKeys) : v && typeof v === "object" ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])])) : v;
const abi = sortKeys(artifact.abi);
const out = `// Generated by web/scripts/gen-abi.mjs from src/SwarmExit.sol. Do not edit by hand.
export const swarmExitAbi = ${JSON.stringify(abi, null, 2)} as const;
`;
fs.writeFileSync(path.join(here, "..", "src/abi/swarmExit.ts"), out);
console.log("wrote web/src/abi/swarmExit.ts with", abi.length, "entries");
